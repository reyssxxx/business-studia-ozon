def row(name,vals,src='',st='',fmt='#,##0',inp=False,bold=False):
    global r
    ws.cell(r,1,name).font=B if bold else Font()
    for j,v in enumerate(vals):
        c=ws.cell(r,2+j,v); c.number_format=fmt; c.font=BL if inp else (B if bold else Font())
    ws.cell(r,5,src); ws.cell(r,6,st); r+=1; return r-1
def sec(t):
    global r
    r+=1; ws.cell(r,1,t).font=B
    for j in range(1,7): ws.cell(r,j).fill=H
    r+=1
